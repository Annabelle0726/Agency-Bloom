"""Build the small, embedded opening-only WOFF from an OFL-licensed source.

uv run --no-project --with fonttools==4.61.1 python tools/prepare-opening-font.py --source PATH
Source: https://raw.githubusercontent.com/google/fonts/main/ofl/notoserifsc/NotoSerifSC%5Bwght%5D.ttf
The full upstream font stays outside the shipped application.
"""
import argparse
import ast
import base64
import hashlib
import io
import json
from pathlib import Path
import re

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source', type=Path, required=True)
args = parser.parse_args()
source = args.source.read_bytes()
component = (ROOT / 'apps/miniprogram/src/components/WelcomeOpening.vue').read_text(encoding='utf-8')
texts = []
for group in re.findall(r'title:\s*(\[[^\]]+\])', component):
    texts.extend(ast.literal_eval(group))
for line in re.findall(r"emphasis:\s*('(?:\\.|[^'])*')", component):
    texts.append(ast.literal_eval(line))
assert len(texts) == 15, 'Expected ten title lines and five closing passages'
texts.append('给自己一点空间')
codepoints = sorted({ord(char) for char in ''.join(texts) if not char.isspace()} | {32})
font = TTFont(io.BytesIO(source))
assert all(cp in font.getBestCmap() for cp in codepoints), 'Source is missing opening glyphs'
options = subset.Options()
options.layout_features = []
options.hinting = False
options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
options.name_legacy = True
options.name_languages = [0x409]
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=codepoints)
subsetter.subset(font)
font = instantiateVariableFont(font, {'wght': 400}, inplace=True)
names = {1: 'Bloom Opening Serif', 2: 'Regular', 3: 'BloomOpeningSerif-Regular-1',
         4: 'Bloom Opening Serif Regular', 6: 'BloomOpeningSerif-Regular',
         16: 'Bloom Opening Serif', 17: 'Regular'}
for record in font['name'].names:
    if record.nameID in names:
        record.string = names[record.nameID].encode(record.getEncoding())
assert any(record.nameID == 13 for record in font['name'].names), 'Keep embedded font license metadata'
font.flavor = 'woff'
buffer = io.BytesIO()
font.save(buffer)
data = buffer.getvalue()
assert len(data) < 40_000, 'Keep the embedded font below the uni-app guidance limit'
encoded = base64.b64encode(data).decode('ascii')
stylesheet = (
    '/*! Bloom Opening Serif: opening-only subset of Noto Serif SC, SIL OFL 1.1.\n'
    ' * Copyright Google Inc.; source and license: design/fonts/opening-serif/.\n'
    ' * Generated by tools/prepare-opening-font.py; license metadata is retained. */\n'
    "@font-face {\n  font-family:'Bloom Opening Serif';\n"
    f"  src:url('data:font/woff;base64,{encoded}') format('woff');\n"
    '  font-style:normal; font-weight:400; font-display:swap;\n}\n'
)
(ROOT / 'apps/miniprogram/src/opening-serif.scss').write_text(stylesheet, encoding='utf-8', newline='\n')
manifest = {
    'family': 'Bloom Opening Serif', 'sourceFamily': 'Noto Serif SC', 'weight': 400,
    'sourceUrl': 'https://raw.githubusercontent.com/google/fonts/main/ofl/notoserifsc/NotoSerifSC%5Bwght%5D.ttf',
    'sourceSha256': hashlib.sha256(source).hexdigest(), 'woffSha256': hashlib.sha256(data).hexdigest(),
    'woffBytes': len(data), 'codepoints': codepoints, 'fontToolsVersion': '4.61.1',
    'license': 'SIL Open Font License 1.1',
}
(ROOT / 'design/fonts/opening-serif/manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
print(f'PASS: embedded regular WOFF, {len(codepoints)} characters, {len(data)} bytes; no runtime font request')
