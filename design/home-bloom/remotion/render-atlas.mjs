import path from 'node:path';
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {bundle} from '@remotion/bundler';
import {renderFrames,selectComposition} from '@remotion/renderer';
import sharp from 'sharp';

const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../../..');
const out=path.join(root,'output/home-bloom/remotion-greeting');
await fs.mkdir(out,{recursive:true});
const serveUrl=await bundle({entryPoint:path.join(here,'src/index.ts'),publicDir:path.join(here,'public'),outDir:path.join(out,'bundle')});
const browserExecutable=process.env.REMOTION_BROWSER_EXECUTABLE || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const composition=await selectComposition({serveUrl,id:'BloomHello',browserExecutable});
const framesDir=path.join(out,'frames');
await renderFrames({serveUrl,composition,outputDir:framesDir,imageFormat:'png',browserExecutable,concurrency:2,
  onFrameUpdate:count=>{if(count%12===0)process.stdout.write(`Rendered ${count}/${composition.durationInFrames} frames\n`);}});
const frames=(await fs.readdir(framesDir)).filter(name=>name.endsWith('.png')).sort();
if(frames.length!==composition.durationInFrames)throw Error('Unexpected frame count');
const columns=6,rows=Math.ceil(frames.length/columns),width=composition.width,height=composition.height;
const inputs=frames.map((name,index)=>({input:path.join(framesDir,name),left:(index%columns)*width,top:Math.floor(index/columns)*height}));
const asset=path.join(root,'apps/miniprogram/src/static/bloom-greeting.png');
await sharp({create:{width:columns*width,height:rows*height,channels:4,background:{r:0,g:0,b:0,alpha:0}}}).composite(inputs).png({palette:true,quality:100,effort:9}).toFile(asset);
const metadata={source:'Remotion BloomHello',fps:composition.fps,frames:frames.length,columns,rows,frameWidth:width,frameHeight:height,durationMs:frames.length/composition.fps*1000,asset:'/static/bloom-greeting.png'};
await fs.writeFile(path.join(root,'apps/miniprogram/src/bloom-greeting.generated.json'),JSON.stringify(metadata,null,2)+'\n');
const keyframes=frames.map((_,index)=>{
 const percent=index/frames.length*100;
 return `  ${percent.toFixed(6)}% { transform:translate(${-(index%columns)/columns*100}%,${-Math.floor(index/columns)/rows*100}%); }`;
});
keyframes.push(`  100% { transform:translate(${-(frames.length-1)%columns/columns*100}%,${-Math.floor((frames.length-1)/columns)/rows*100}%); }`);
await fs.writeFile(path.join(root,'apps/miniprogram/src/bloom-greeting.generated.scss'),'/* Generated by the Remotion greeting renderer. */\n@keyframes bloom-greet {\n'+keyframes.join('\n')+'\n}\n');
const first=await sharp(path.join(framesDir,frames[0])).raw().toBuffer();
const last=await sharp(path.join(framesDir,frames.at(-1))).raw().toBuffer();
if(!first.equals(last))throw Error('Greeting must return to its exact resting frame');
const report={...metadata,bytes:(await fs.stat(asset)).size,alpha:(await sharp(asset).metadata()).hasAlpha,restFrameMatches:true};
await fs.writeFile(path.join(out,'render-report.json'),JSON.stringify(report,null,2)+'\n');
console.log(report);
